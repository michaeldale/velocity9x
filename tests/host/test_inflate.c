/*
 * Every decode lands in out_buffer with a band of canary bytes straight
 * after the capacity it was given; a write past the capacity shows up as a
 * changed canary whatever status came back.
 */
#define OUT_MAX      65536ul
#define CANARY_BYTES 64u
#define CANARY_VALUE 0xA5u

static v9x_u8 out_buffer[OUT_MAX + CANARY_BYTES];

static v9x_u16 run_inflate(const v9x_u8 *input,
                           v9x_u32 input_length,
                           v9x_u32 capacity,
                           v9x_u32 *output_length)
{
    unsigned int i;
    unsigned int intact;
    v9x_u16 status;

    for (i = 0u; i < CANARY_BYTES; ++i) {
        out_buffer[capacity + i] = (v9x_u8)CANARY_VALUE;
    }
    status = v9x_inflate(input, input_length, out_buffer, capacity,
                         output_length);
    intact = 1u;
    for (i = 0u; i < CANARY_BYTES; ++i) {
        if (out_buffer[capacity + i] != (v9x_u8)CANARY_VALUE) {
            intact = 0u;
        }
    }
    IFCHECK(intact == 1u);
    IFCHECK(*output_length <= capacity);
    return status;
}

/* The fixture_repeat input, regenerated. */
static v9x_u8 repeat_byte(unsigned long i)
{
    static const char phrase[] = "The quick brown fox jumps over the lazy dog. ";

    if ((i % 997ul) == 0ul) {
        return (v9x_u8)((i / 997ul) & 0xFFul);
    }
    return (v9x_u8)phrase[i % 45ul];
}

/* A deterministic generator for the fuzz passes (the C89 rand() is not
 * specified closely enough to give the same run on two compilers). */
static unsigned long fuzz_seed = 1ul;

static unsigned long fuzz_next(void)
{
    fuzz_seed = (fuzz_seed * 1103515245ul + 12345ul) & 0x7FFFFFFFul;
    return fuzz_seed >> 8;
}

