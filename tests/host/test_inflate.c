static void test_crc32(void)
{
    static const v9x_u8 check[] = "123456789";
    v9x_u32 crc;
    unsigned long i;

    /* The catalogued check value for CRC-32/ISO-HDLC, the zip CRC. */
    IFCHECK(v9x_crc32(check, 9ul) == 0xCBF43926ul);
    IFCHECK(v9x_crc32(check, 0ul) == 0ul);

    /* Incremental equals one-shot, split at an odd place. */
    crc = v9x_crc32_update(V9X_CRC32_INITIAL, check, 4ul);
    crc = v9x_crc32_update(crc, check + 4, 5ul);
    IFCHECK(v9x_crc32_final(crc) == 0xCBF43926ul);

    /* Against the generator's independent CRC over 50000 bytes. */
    crc = V9X_CRC32_INITIAL;
    for (i = 0ul; i < FIXTURE_REPEAT_LENGTH; ++i) {
        v9x_u8 b = repeat_byte(i);
        crc = v9x_crc32_update(crc, &b, 1ul);
    }
    IFCHECK(v9x_crc32_final(crc) == FIXTURE_REPEAT_CRC);
}

