[CmdletBinding()]
param(
    [string]$FirmwareDirectory
)

# Generates src\chipsets\ati\evergreen\eg_cp_microcode.c, the Evergreen
# (Cedar) command processor microcode as host-order dword arrays, from
# linux-firmware's radeon/CEDAR_pfp.bin and radeon/CEDAR_me.bin and its
# LICENSES/LICENSE.radeon. Each file must match the SHA-256 recorded here,
# so a regenerated array is the one measured on M-BXMFA8
# (docs\decisions\2026-10-26-cedar-cp-runs-amd-microcode.md).
#
# The .bin files hold big-endian dwords, which Linux's
# evergreen_cp_load_microcode converts with be32_to_cpup; the arrays hold
# the converted values, written to the data ports as they stand.

$ErrorActionPreference = 'Stop'
$repoRoot = Split-Path -Parent $PSScriptRoot
if (-not $FirmwareDirectory) {
    $FirmwareDirectory = Join-Path $repoRoot 'build\external\evergreen\firmware'
}

$expected = @{
    'CEDAR_pfp.bin'  = 'bf614bcdd72fd23a919d2bf39ec065824f0c327e50b9ba3d9d39cb675764fcf3'
    'CEDAR_me.bin'   = '86cec272c18673356c0e8d774d7ed48976baa631f79734225522a928e9089db4'
    'LICENSE.radeon' = 'fc6223d4bfe9f2f9e2eddc44b9fe5721d0caf49f01cb08d602906add686d8c6f'
}
foreach ($name in $expected.Keys) {
    $path = Join-Path $FirmwareDirectory $name
    if (-not (Test-Path -LiteralPath $path)) {
        throw "Missing $path."
    }
    $hash = (Get-FileHash -LiteralPath $path -Algorithm SHA256).Hash.ToLowerInvariant()
    if ($hash -ne $expected[$name]) {
        throw "$name has SHA-256 $hash, expected $($expected[$name])."
    }
}

function Format-V9xMicrocode {
    param([string]$Path, [int]$Dwords, [string]$Symbol)
    $bytes = [IO.File]::ReadAllBytes($Path)
    if ($bytes.Length -ne $Dwords * 4) {
        throw "$Path is $($bytes.Length) bytes, expected $($Dwords * 4)."
    }
    $lines = @("const v9x_u32 $Symbol[$Dwords] = {")
    for ($row = 0; $row -lt $Dwords; $row += 4) {
        $cells = @()
        for ($column = 0; $column -lt 4 -and $row + $column -lt $Dwords; ++$column) {
            $at = ($row + $column) * 4
            $value = ([uint32]$bytes[$at] -shl 24) -bor ([uint32]$bytes[$at + 1] -shl 16) -bor
                     ([uint32]$bytes[$at + 2] -shl 8) -bor [uint32]$bytes[$at + 3]
            $cells += ('0x{0:x8}ul' -f $value)
        }
        $separator = if ($row + 4 -lt $Dwords) { ',' } else { '' }
        $lines += '    ' + ($cells -join ', ') + $separator
    }
    $lines += '};'
    return $lines
}

$license = Get-Content -LiteralPath (Join-Path $FirmwareDirectory 'LICENSE.radeon')
$output = @(
    '/*',
    ' * The AMD Evergreen (Cedar) command processor microcode: the PFP (1120',
    ' * dwords) and ME (1376 dwords) images Linux evergreen_cp_load_microcode',
    ' * writes to CP_PFP_UCODE_DATA and CP_ME_RAM_DATA, as host-order dwords.',
    ' *',
    ' * Generated by scripts\gen-evergreen-microcode.ps1 from linux-firmware''s',
    ' * radeon/CEDAR_pfp.bin (SHA-256',
    " * $($expected['CEDAR_pfp.bin']))",
    ' * and radeon/CEDAR_me.bin (SHA-256',
    " * $($expected['CEDAR_me.bin'])).",
    ' * Measured loading and running on M-BXMFA8''s HD 5450',
    ' * (docs\decisions\2026-10-26-cedar-cp-runs-amd-microcode.md).',
    ' * Do not edit: regenerate from the .bin files.',
    ' *',
    ' * linux-firmware WHENCE: "Licence: Redistributable. See LICENSE.radeon',
    ' * for details." LICENSE.radeon, reproduced as its redistribution terms',
    ' * require:',
    ' *'
)
foreach ($line in $license) {
    $output += (' * ' + $line).TrimEnd()
}
$output += @(
    ' */',
    '#include "velocity9x/eg_cp_microcode.h"',
    ''
)
$output += Format-V9xMicrocode -Path (Join-Path $FirmwareDirectory 'CEDAR_pfp.bin') -Dwords 1120 -Symbol 'v9x_eg_pfp_microcode'
$output += ''
$output += Format-V9xMicrocode -Path (Join-Path $FirmwareDirectory 'CEDAR_me.bin') -Dwords 1376 -Symbol 'v9x_eg_me_microcode'

$target = Join-Path $repoRoot 'src\chipsets\ati\evergreen\eg_cp_microcode.c'
[IO.File]::WriteAllText($target, (($output -join "`r`n") + "`r`n"), [Text.Encoding]::ASCII)
Write-Output "Wrote $target."
