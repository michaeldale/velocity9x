[CmdletBinding()]
param(
    [string]$FirmwareDirectory
)

# Generates src\chipsets\ati\cik\cik_sdma_microcode.c, the AMD Mullins
# (Radeon R3E, GCN 2) SDMA engine's microcode as host-order dwords, from
# linux-firmware's amdgpu/mullins_sdma.bin and its LICENSE.amdgpu. Each
# file must match the SHA-256 recorded here, so a regenerated array is the
# one measured on M-JJN1ZZ
# (docs\decisions\2026-11-08-mullins-sdma-write-probe.md).
#
# The image is gen-carrizo-microcode.ps1's format: a little-endian
# common_firmware_header (Linux amdgpu_ucode.h) and a payload; the array is
# the payload from ucode_array_offset_bytes, ucode_size_bytes long, which
# Linux cik_sdma_load_microcode writes to SDMA0_UCODE_DATA with
# le32_to_cpup. The header's ucode_version goes to SDMA0_UCODE_ADDR after
# the load.

$ErrorActionPreference = 'Stop'
$repoRoot = Split-Path -Parent $PSScriptRoot
if (-not $FirmwareDirectory) {
    $FirmwareDirectory = Join-Path $repoRoot 'build\external\mullins\firmware'
}

$expected = @{
    'mullins_sdma.bin' = '638602157d38a25e584e81710c9c3a36731c52599d92e010b77dd53890dc662a'
    'LICENSE.amdgpu'   = '572872598565dc3513470de971a32bf9db301f47afeef3636345eadae33b2eee'
}
foreach ($name in $expected.Keys) {
    $path = Join-Path $FirmwareDirectory $name
    if (-not (Test-Path -LiteralPath $path)) {
        throw "Missing $path."
    }
    $hash = (Get-FileHash -LiteralPath $path -Algorithm SHA256).Hash.ToLowerInvariant()
    if ($hash -ne $expected[$name]) {
        throw "$name has SHA-256 $hash, expected $($expected[$name])."
    }
}

$bytes = [IO.File]::ReadAllBytes((Join-Path $FirmwareDirectory 'mullins_sdma.bin'))
$sizeBytes = [BitConverter]::ToUInt32($bytes, 0x00)
$ucodeVersion = [BitConverter]::ToUInt32($bytes, 0x10)
$ucodeBytes = [BitConverter]::ToUInt32($bytes, 0x14)
$arrayOffset = [BitConverter]::ToUInt32($bytes, 0x18)
if ($sizeBytes -ne $bytes.Length -or ($ucodeBytes % 4) -ne 0 -or
    $arrayOffset + $ucodeBytes -gt $bytes.Length) {
    throw 'mullins_sdma.bin has an inconsistent firmware header.'
}
$dwords = $ucodeBytes / 4

$license = Get-Content -LiteralPath (Join-Path $FirmwareDirectory 'LICENSE.amdgpu')
$output = @(
    '/*',
    " * The AMD Mullins SDMA engine microcode: the $dwords-dword image Linux",
    ' * cik_sdma_load_microcode writes to SDMA0_UCODE_DATA, as host-order',
    ' * dwords, and the version it then writes to SDMA0_UCODE_ADDR.',
    ' *',
    ' * Generated by scripts\gen-mullins-microcode.ps1 from linux-firmware''s',
    ' * amdgpu/mullins_sdma.bin (SHA-256',
    " * $($expected['mullins_sdma.bin'])).",
    ' * Measured loading and running on M-JJN1ZZ''s Radeon R3E',
    ' * (docs\decisions\2026-11-08-mullins-sdma-write-probe.md).',
    ' * Do not edit: regenerate from the .bin file.',
    ' *',
    ' * linux-firmware WHENCE: "Licence: Redistributable. See LICENSE.amdgpu',
    ' * for details." LICENSE.amdgpu, reproduced as its redistribution terms',
    ' * require:',
    ' *'
)
foreach ($line in $license) {
    $output += (' * ' + $line).TrimEnd()
}
$output += @(
    ' */',
    '#include "velocity9x/cik_sdma_microcode.h"',
    '',
    ('const v9x_u32 v9x_cik_sdma_microcode_version = 0x{0:x8}ul;' -f $ucodeVersion),
    '',
    "const v9x_u32 v9x_cik_sdma_microcode[$dwords] = {"
)
for ($row = 0; $row -lt $dwords; $row += 4) {
    $cells = @()
    for ($column = 0; $column -lt 4 -and $row + $column -lt $dwords; ++$column) {
        $value = [BitConverter]::ToUInt32($bytes, $arrayOffset + ($row + $column) * 4)
        $cells += ('0x{0:x8}ul' -f $value)
    }
    $separator = if ($row + 4 -lt $dwords) { ',' } else { '' }
    $output += '    ' + ($cells -join ', ') + $separator
}
$output += '};'

$targetDir = Join-Path $repoRoot 'src\chipsets\ati\cik'
New-Item -ItemType Directory -Force -Path $targetDir | Out-Null
$target = Join-Path $targetDir 'cik_sdma_microcode.c'
[IO.File]::WriteAllText($target, (($output -join "`r`n") + "`r`n"), [Text.Encoding]::ASCII)
Write-Output "Wrote $target ($dwords dwords, ucode version 0x$('{0:x}' -f $ucodeVersion))."
