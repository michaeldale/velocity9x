[CmdletBinding()]
param(
    [string]$Header
)

# Generates src\chipsets\ati\vi\vi_clear_state.c, the GFX8 ("VI") context
# register defaults Linux's gfx_v8_0_cp_gfx_start sends between
# PREAMBLE_CNTL's begin and end of clear state, from Linux amdgpu's
# clearstate_vi.h (MIT, AMD 2014; the notice goes with the table). The
# header must match the SHA-256 recorded here, so a regenerated table is
# the one the CP was given on M-XP7053.
#
# clearstate_vi.h holds seven runs of context registers (vi_SECT_CONTEXT_def_1
# .. _7) and vi_SECT_CONTEXT_defs, the dword index each run starts at and its
# length. The output keeps that shape: one array of every value in run order
# and one table of {first register, count} runs.

$ErrorActionPreference = 'Stop'
$repoRoot = Split-Path -Parent $PSScriptRoot
if (-not $Header) {
    $Header = Join-Path $repoRoot 'build\external\carrizo\linux\drivers\gpu\drm\amd\amdgpu\clearstate_vi.h'
}
$expected = '070c2d006921b1bc9f41f9cb569213df62f8321c5a84aeeaa404e1bce8ee982e'
$hash = (Get-FileHash -LiteralPath $Header -Algorithm SHA256).Hash.ToLowerInvariant()
if ($hash -ne $expected) {
    throw "clearstate_vi.h has SHA-256 $hash, expected $expected."
}

$text = [IO.File]::ReadAllText($Header)
$license = [regex]::Match($text, '^/\*(.*?)\*/', 'Singleline').Groups[1].Value
$arrays = @{}
foreach ($match in [regex]::Matches($text,
        'static const unsigned int (vi_SECT_CONTEXT_def_\d+)\[\]\s*=\s*\{(.*?)\};',
        'Singleline')) {
    $values = @()
    foreach ($line in ($match.Groups[2].Value -split "`n")) {
        # A value, or the bare 0 the header writes for a HOLE.
        $value = [regex]::Match($line, '^\s*0x([0-9a-fA-F]+)\s*,|^\s*(0)\s*,')
        if ($value.Groups[1].Success) {
            $values += [Convert]::ToUInt32($value.Groups[1].Value, 16)
        } elseif ($value.Groups[2].Success) {
            $values += [uint32]0
        }
    }
    $arrays[$match.Groups[1].Value] = $values
}
$runs = @()
foreach ($match in [regex]::Matches($text,
        '\{\s*(vi_SECT_CONTEXT_def_\d+)\s*,\s*(0x[0-9a-fA-F]+)\s*,\s*(\d+)\s*\}')) {
    $name = $match.Groups[1].Value
    $count = [int]$match.Groups[3].Value
    if (-not $arrays.ContainsKey($name) -or $arrays[$name].Count -ne $count) {
        throw "$name has $($arrays[$name].Count) values, the extent table says $count."
    }
    $runs += @{ Name = $name; First = [Convert]::ToUInt32($match.Groups[2].Value, 16); Count = $count }
}
if ($runs.Count -eq 0) {
    throw 'No context runs found in clearstate_vi.h.'
}
$total = ($runs | ForEach-Object { $_.Count } | Measure-Object -Sum).Sum

$output = @(
    '/*',
    ' * The GFX8 ("VI") clear-state context registers: Linux amdgpu''s',
    ' * clearstate_vi.h vi_cs_data, which gfx_v8_0_cp_gfx_start sends as',
    ' * SET_CONTEXT_REG runs inside the clear-state preamble.',
    ' *',
    ' * Generated by scripts\gen-carrizo-clear-state.ps1 from clearstate_vi.h',
    " * (SHA-256 $hash).",
    ' * Do not edit: regenerate from the header.',
    ' *',
    ' * clearstate_vi.h''s notice, reproduced as its licence requires:',
    ' *'
)
foreach ($line in ($license -split "`n")) {
    $clean = $line.TrimEnd("`r").TrimStart()
    if ($clean.StartsWith('*')) {
        $clean = $clean.Substring(1)
    }
    $output += (' *' + $clean).TrimEnd()
}
$output += @(
    ' */',
    '#include "velocity9x/vi_clear_state.h"',
    '',
    "const v9x_u32 v9x_vi_clear_state_values[$total] = {"
)
$all = @()
foreach ($run in $runs) {
    $all += $arrays[$run.Name]
}
for ($row = 0; $row -lt $all.Count; $row += 4) {
    $cells = @()
    for ($column = 0; $column -lt 4 -and $row + $column -lt $all.Count; ++$column) {
        $cells += ('0x{0:x8}ul' -f $all[$row + $column])
    }
    $separator = if ($row + 4 -lt $all.Count) { ',' } else { '' }
    $output += '    ' + ($cells -join ', ') + $separator
}
$output += @('};', '', "const struct v9x_vi_clear_state_run v9x_vi_clear_state_runs[$($runs.Count)] = {")
for ($index = 0; $index -lt $runs.Count; ++$index) {
    $separator = if ($index + 1 -lt $runs.Count) { ',' } else { '' }
    $output += ('    {{ 0x{0:x5}ul, {1}ul }}{2}' -f $runs[$index].First, $runs[$index].Count, $separator)
}
$output += '};'

$target = Join-Path $repoRoot 'src\chipsets\ati\vi\vi_clear_state.c'
[IO.File]::WriteAllText($target, (($output -join "`r`n") + "`r`n"), [Text.Encoding]::ASCII)
Write-Output "Wrote $target ($($runs.Count) runs, $total dwords, header SHA-256 $hash)."
