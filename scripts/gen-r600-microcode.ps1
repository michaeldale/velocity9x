[CmdletBinding()]
param(
    [string]$FirmwareDirectory
)

# Generates src\chipsets\ati\r600\r6_cp_microcode.c, the R6xx command
# processor microcode for the HD 2600 XT (RV630) as host-order dword
# arrays, from linux-firmware's radeon/RV630_pfp.bin and RV630_me.bin and
# LICENSE.radeon (fetched 2026-11-13 into build\external\rv630\firmware).
# Each file must match the SHA-256 recorded here, so a regenerated array is
# the one measured.
#
# Sizes are Linux radeon_ucode.h's: the PFP 576 dwords
# (R600_PFP_UCODE_SIZE), the ME three times 1792 (R600_PM4_UCODE_SIZE,
# r600_cp_load_microcode writes R600_PM4_UCODE_SIZE * 3 dwords). The .bin
# files hold big-endian dwords, which r600_cp_load_microcode converts with
# be32_to_cpup; the arrays hold the converted values, written to the data
# ports as they stand.

$ErrorActionPreference = 'Stop'
$repoRoot = Split-Path -Parent $PSScriptRoot
if (-not $FirmwareDirectory) {
    $FirmwareDirectory = Join-Path $repoRoot 'build\external\rv630\firmware'
}

$expected = @{
    'RV630_pfp.bin'  = 'c0f58b75401acef29861a399430ce51681a39771ca30d020de24358dc1909246'
    'RV630_me.bin'   = '2a7e310ab6fd2d8c466ddbb394ae0da26303b1da9f924c04d7cbc4f47836e9e0'
    'LICENSE.radeon' = 'fc6223d4bfe9f2f9e2eddc44b9fe5721d0caf49f01cb08d602906add686d8c6f'
}
foreach ($name in $expected.Keys) {
    $path = Join-Path $FirmwareDirectory $name
    if (-not (Test-Path -LiteralPath $path)) {
        throw "Missing $path."
    }
    $hash = (Get-FileHash -LiteralPath $path -Algorithm SHA256).Hash.ToLowerInvariant()
    if ($hash -ne $expected[$name]) {
        throw "$name has SHA-256 $hash, expected $($expected[$name])."
    }
}

function Format-V9xMicrocode {
    param([string]$Path, [int]$Dwords, [string]$Symbol)
    $bytes = [IO.File]::ReadAllBytes($Path)
    if ($bytes.Length -ne $Dwords * 4) {
        throw "$Path is $($bytes.Length) bytes, expected $($Dwords * 4)."
    }
    $lines = @("const v9x_u32 $Symbol[$Dwords] = {")
    for ($row = 0; $row -lt $Dwords; $row += 4) {
        $cells = @()
        for ($column = 0; $column -lt 4 -and $row + $column -lt $Dwords; ++$column) {
            $at = ($row + $column) * 4
            $value = ([uint32]$bytes[$at] -shl 24) -bor ([uint32]$bytes[$at + 1] -shl 16) -bor
                     ([uint32]$bytes[$at + 2] -shl 8) -bor [uint32]$bytes[$at + 3]
            $cells += ('0x{0:x8}ul' -f $value)
        }
        $separator = if ($row + 4 -lt $Dwords) { ',' } else { '' }
        $lines += '    ' + ($cells -join ', ') + $separator
    }
    $lines += '};'
    return $lines
}

$license = Get-Content -LiteralPath (Join-Path $FirmwareDirectory 'LICENSE.radeon')
$output = @(
    '/*',
    ' * The ATI R6xx command processor microcode for the HD 2600 XT (RV630):',
    ' * the PFP (576 dwords) and ME (5376 dwords, three times',
    ' * R600_PM4_UCODE_SIZE) images Linux r600_cp_load_microcode writes to',
    ' * CP_PFP_UCODE_DATA and CP_ME_RAM_DATA, as host-order dwords.',
    ' *',
    ' * Generated by scripts\gen-r600-microcode.ps1 from linux-firmware''s',
    ' * radeon/RV630_pfp.bin (SHA-256',
    " * $($expected['RV630_pfp.bin']))",
    ' * and radeon/RV630_me.bin (SHA-256',
    " * $($expected['RV630_me.bin'])),",
    ' * measured loading and running on M-NZHWBR''s HD 2600 XT',
    ' * (docs\decisions\2026-11-13-rv630-cp-ring-test.md).',
    ' * Do not edit: regenerate from the .bin files.',
    ' *',
    ' * linux-firmware WHENCE: "Licence: Redistributable. See LICENSE.radeon',
    ' * for details." LICENSE.radeon, reproduced as its redistribution terms',
    ' * require:',
    ' *'
)
foreach ($line in $license) {
    $output += (' * ' + $line).TrimEnd()
}
$output += @(
    ' */',
    '#include "velocity9x/r6_cp_microcode.h"',
    ''
)
$output += Format-V9xMicrocode -Path (Join-Path $FirmwareDirectory 'RV630_pfp.bin') -Dwords 576 -Symbol 'v9x_r6_rv630_pfp_microcode'
$output += ''
$output += Format-V9xMicrocode -Path (Join-Path $FirmwareDirectory 'RV630_me.bin') -Dwords 5376 -Symbol 'v9x_r6_rv630_me_microcode'

$target = Join-Path $repoRoot 'src\chipsets\ati\r600\r6_cp_microcode.c'
[IO.File]::WriteAllText($target, (($output -join "`r`n") + "`r`n"), [Text.Encoding]::ASCII)
Write-Output "Wrote $target."
