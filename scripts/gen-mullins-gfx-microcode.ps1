[CmdletBinding()]
param(
    [string]$FirmwareDirectory
)

# Generates src\chipsets\ati\cik\cik_gfx_microcode.c, the AMD Mullins
# graphics engine's microcode as host-order dwords - the RLC's and the
# CP's three microengines' (PFP, CE, ME) - from linux-firmware's
# amdgpu/mullins_{rlc,pfp,ce,me}.bin and LICENSE.amdgpu. Each file must
# match the SHA-256 recorded here, the images V9XCKCP and V9XCK3D loaded
# on M-JJN1ZZ (docs\decisions\2026-11-08-mullins-cp-ring-test.md). A copy
# of gen-carrizo-gfx-microcode.ps1.
#
# An amdgpu image is a little-endian common_firmware_header (Linux
# amdgpu_ucode.h) and a payload; the array is the payload from
# ucode_array_offset_bytes, ucode_size_bytes long, which Linux
# gfx_v7_0_rlc_resume and gfx_v7_0_cp_gfx_load_microcode write to each
# engine's data port. The header's ucode_version goes to the address port
# after the load. All four headers are version 1.0 on Mullins.

$ErrorActionPreference = 'Stop'
$repoRoot = Split-Path -Parent $PSScriptRoot
if (-not $FirmwareDirectory) {
    $FirmwareDirectory = Join-Path $repoRoot 'build\external\mullins\firmware'
}

$expected = [ordered]@{
    'mullins_rlc.bin' = '21e4d2973b8388864fb489a3c7cbbc55a13b787b884027ff79bb4cd71ed86ce1'
    'mullins_pfp.bin' = '11e6b126b1528374ee5d763edbf13b4966a35169e9ac8028f735e617cbf4211f'
    'mullins_ce.bin'  = '938d3f602ce9029ac6188bda2eea036c3b68572a50ff407374e6e43b0865f374'
    'mullins_me.bin'  = 'bf462933ee4a6412b20c41f5bdf9ce1240c31ee691b3206348d00a6d024189d2'
    'LICENSE.amdgpu'  = '572872598565dc3513470de971a32bf9db301f47afeef3636345eadae33b2eee'
}
foreach ($name in $expected.Keys) {
    $path = Join-Path $FirmwareDirectory $name
    if (-not (Test-Path -LiteralPath $path)) {
        throw "Missing $path."
    }
    $hash = (Get-FileHash -LiteralPath $path -Algorithm SHA256).Hash.ToLowerInvariant()
    if ($hash -ne $expected[$name]) {
        throw "$name has SHA-256 $hash, expected $($expected[$name])."
    }
}

# Name in C, file, header major version Linux reads it with.
$images = @(
    @{ Name = 'rlc'; File = 'mullins_rlc.bin'; Major = 1 },
    @{ Name = 'pfp'; File = 'mullins_pfp.bin'; Major = 1 },
    @{ Name = 'ce';  File = 'mullins_ce.bin';  Major = 1 },
    @{ Name = 'me';  File = 'mullins_me.bin';  Major = 1 }
)

$license = Get-Content -LiteralPath (Join-Path $FirmwareDirectory 'LICENSE.amdgpu')
$output = @(
    '/*',
    ' * The AMD Mullins graphics engine microcode: the RLC''s and the CP''s PFP,',
    ' * CE and ME images Linux gfx_v7_0.c writes to each engine''s data',
    ' * port, as host-order dwords, and the versions it then',
    ' * writes to the address ports.',
    ' *',
    ' * Generated by scripts\gen-mullins-gfx-microcode.ps1 from linux-firmware''s',
    ' * amdgpu/mullins_{rlc,pfp,ce,me}.bin (SHA-256 in the script). Measured',
    ' * loading and running on M-JJN1ZZ''s Radeon R3E',
    ' * (docs\decisions\2026-11-08-mullins-cp-ring-test.md).',
    ' * Do not edit: regenerate from the .bin files.',
    ' *',
    ' * linux-firmware WHENCE: "Licence: Redistributable. See LICENSE.amdgpu',
    ' * for details." LICENSE.amdgpu, reproduced as its redistribution terms',
    ' * require:',
    ' *'
)
foreach ($line in $license) {
    $output += (' * ' + $line).TrimEnd()
}
$output += @(
    ' */',
    '#include "velocity9x/cik_gfx_microcode.h"'
)

$summary = @()
foreach ($image in $images) {
    $bytes = [IO.File]::ReadAllBytes((Join-Path $FirmwareDirectory $image.File))
    $sizeBytes = [BitConverter]::ToUInt32($bytes, 0x00)
    $headerMajor = [BitConverter]::ToUInt16($bytes, 0x08)
    $ucodeVersion = [BitConverter]::ToUInt32($bytes, 0x10)
    $ucodeBytes = [BitConverter]::ToUInt32($bytes, 0x14)
    $arrayOffset = [BitConverter]::ToUInt32($bytes, 0x18)
    if ($sizeBytes -ne $bytes.Length -or $headerMajor -ne $image.Major -or
        ($ucodeBytes % 4) -ne 0 -or $ucodeBytes -eq 0 -or
        $arrayOffset + $ucodeBytes -gt $bytes.Length) {
        throw "$($image.File) has an inconsistent firmware header."
    }
    $dwords = $ucodeBytes / 4
    $upper = $image.Name.ToUpperInvariant()
    $output += @(
        '',
        ('const v9x_u32 v9x_cik_{0}_microcode_version = 0x{1:x8}ul;' -f $image.Name, $ucodeVersion),
        "const v9x_u32 v9x_cik_$($image.Name)_microcode[V9X_CIK_$($upper)_MICROCODE_DWORDS] = {"
    )
    for ($row = 0; $row -lt $dwords; $row += 4) {
        $cells = @()
        for ($column = 0; $column -lt 4 -and $row + $column -lt $dwords; ++$column) {
            $value = [BitConverter]::ToUInt32($bytes, $arrayOffset + ($row + $column) * 4)
            $cells += ('0x{0:x8}ul' -f $value)
        }
        $separator = if ($row + 4 -lt $dwords) { ',' } else { '' }
        $output += '    ' + ($cells -join ', ') + $separator
    }
    $output += '};'
    $summary += ('{0} {1} dwords, version 0x{2:x}' -f $image.Name, $dwords, $ucodeVersion)
}

$target = Join-Path $repoRoot 'src\chipsets\ati\cik\cik_gfx_microcode.c'
[IO.File]::WriteAllText($target, (($output -join "`r`n") + "`r`n"), [Text.Encoding]::ASCII)
Write-Output "Wrote $target ($($summary -join '; '))."
